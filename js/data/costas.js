// Cajas de cada contorno (descartan casi todas las pruebas de punto en polígono).
const caja = p => { let a = Infinity, b = Infinity, c = -Infinity, d = -Infinity; for (let i = 0; i < p.length; i += 2) { a = Math.min(a, p[i]); c = Math.max(c, p[i]); b = Math.min(b, p[i + 1]); d = Math.max(d, p[i + 1]); } return [a, b, c, d]; };
const CAJAS = COSTAS.map(caja), CAJAS_LAGOS = LAGOS.map(caja);
function dentro(p, [a, b, c, d], lon, lat) {
  if (lon < a || lon > c || lat < b || lat > d) return false;
  let si = false;
  for (let i = 0, j = p.length - 2; i < p.length; j = i, i += 2) {
    const yi = p[i + 1], yj = p[j + 1];
    if ((yi > lat) !== (yj > lat) && lon < (p[j] - p[i]) * (lat - yi) / (yj - yi) + p[i]) si = !si;
  }
  return si;
}
// ¿Es tierra este punto? (dentro de alguna costa y fuera de los mares interiores)
export function esTierra(lon, lat) {
  let tierra = false;
  for (let k = 0; k < COSTAS.length && !tierra; k++) tierra = dentro(COSTAS[k], CAJAS[k], lon, lat);
  if (!tierra) return false;
  for (let k = 0; k < LAGOS.length; k++) if (dentro(LAGOS[k], CAJAS_LAGOS[k], lon, lat)) return false;
  return true;
}
